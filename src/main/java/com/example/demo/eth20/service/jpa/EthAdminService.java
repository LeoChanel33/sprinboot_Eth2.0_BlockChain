package com.example.demo.eth20.service.jpa;

import com.example.demo.eth20.entity.EthAdmin;
import com.example.demo.eth20.repository.EthAdminRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.data.domain.*;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

@Service @RequiredArgsConstructor @Transactional
public class EthAdminService {
    private final EthAdminRepository repository;

    @Transactional(readOnly = true)
    public Page<EthAdmin> list(int page, int size) {
        if (page < 0 || size < 1 || size > 100) throw new IllegalArgumentException("page >= 0; size must be 1..100");
        return repository.findAll(PageRequest.of(page, size, Sort.by("id")));
    }
    @Transactional(readOnly = true)
    public EthAdmin get(Integer id) {
        return repository.findById(id).orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "EthAdmin not found"));
    }
    public EthAdmin create(EthAdmin body) {
        if (body.getId() != null) throw new IllegalArgumentException("id is generated by the server");
        prepare(body, null, true);
        return repository.saveAndFlush(body);
    }
    public EthAdmin update(Integer id, EthAdmin body) {
        var existing = get(id);
        body.setId(id);
        prepare(body, existing, false);
        return repository.saveAndFlush(body);
    }
    public void delete(Integer id) { repository.delete(get(id)); repository.flush(); }
    private void prepare(EthAdmin body, EthAdmin existing, boolean creating) {
        if (body.getAccount() == null || body.getAccount().isBlank() || body.getAccount().length() > 255)
            throw new IllegalArgumentException("account is required and must be at most 255 characters");
        if (creating ? repository.existsByAccount(body.getAccount()) :
                repository.existsByAccountAndIdNot(body.getAccount(), body.getId()))
            throw new ResponseStatusException(HttpStatus.CONFLICT, "account already exists");
        if (body.getPassword() == null && !creating) body.setPassword(existing.getPassword());
        else body.setPassword(PasswordHash.encode(body.getPassword()));
        if (body.getCreateDate() == null)
            body.setCreateDate(creating ? java.time.LocalDate.now() : existing.getCreateDate());
    }
}